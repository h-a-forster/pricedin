"""The README's result section, rendered from ``evaluation.json`` and the study's data files.

Every number in the section is a field below, and every claim the prose makes in words ("for all
three models", "at every horizon") is asserted before rendering, so a re-scored study cannot
leave the README stating something the results no longer show. ``pricedin report --readme``
rewrites the block between the markers; a test checks the committed README against it.
"""

from __future__ import annotations

import textwrap
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any

from pricedin.eval.hypotheses import primary_family
from pricedin.plots import HORIZON_ORDER
from pricedin.schema import read_jsonl
from pricedin.universe import Study

MARKERS = (
    "<!-- result: generated by `pricedin report --readme` from results/v1; do not edit -->\n",
    "<!-- end of generated result -->\n",
)
HORIZON_WORDS = {"7d": "7 days before", "1d": "1 day before", "1h": "1 hour before"}

TEMPLATE = """\
**No. Without research, Claude adds nothing measurable to the Polymarket price.**

{questions} Polymarket questions, {snapshots} snapshots. Three Claude models forecast each one
without seeing the price. Fitted on questions that resolved by {split}, scored on later ones
({test_rows} test rows per model):

{table}

Brier score on the test period, lower is better. 0.25 is a coin flip.

![Brier by horizon](results/v1/figures/brier_by_horizon.png)

- **The model alone is far worse than the market.** Each model's Brier is {llm_lo}–{llm_hi} at
every horizon. The market sharpens from {market_first} a week out to {market_last} an hour out;
the models barely move.
- **Pooling adds nothing.** Market + LLM beats the recalibrated market by at most {gain_max} Brier,
inside the noise. None of the {tests} pre-registered tests rejects after Holm adjustment (smallest
adjusted p = {p_min}). The weight on the LLM is indistinguishable from zero for {models} alike.
- **Two subgroups to watch.** Category breakdowns are secondary and not Holm-adjusted. {leads} the
pool beats the recalibrated market for all three models, by {lead_lo} to {lead_hi} Brier, with
95% intervals above zero. {lags} lean the other way. Treat this as a lead for a new study, not a
finding.
- **Light news does not help.** {news_snapshots} snapshots had relevant dated headlines. On those
rows the pool scored worse than the recalibrated market at every horizon for every model, by
{news_lo} to {news_hi} Brier. The pools were fitted on only {train_lo} to {train_hi} training rows
per horizon, so read this as no sign of a gain, not as proof that news hurts.
- **No money in it.** Trading the gap between the pool and the market, after fees, earns no more
than trading the recalibrated market alone. The LLM on its own loses money.
"""


class ClaimError(ValueError):
    """The results no longer support a sentence of the README's prose."""


def _require(ok: bool, claim: str) -> None:
    if not ok:
        raise ClaimError(f"the results no longer show: {claim}")


def _model_name(key: str) -> str:
    """``claude-cli:claude-opus-5-5@low|base`` -> ``Claude Opus 5.5``."""
    name = key.split(":", 1)[-1].split("@")[0].split("|")[0]
    parts = name.split("-")
    words = [p.capitalize() for p in parts if not p.isdigit()]
    version = ".".join(p for p in parts if p.isdigit())
    return " ".join(words) + (f" {version}" if version else "")


def _family(key: str) -> str:
    return _model_name(key).split()[1]


def _join(names: list[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def _fields(study: Study, ev: dict[str, Any], featured: str) -> dict[str, str]:
    keys = ev["keys"]
    base = [k for k in keys if k.endswith("|base")]
    news = [k for k in keys if k.endswith("|news")]
    hs = [h for h in HORIZON_ORDER if h in keys[featured]["by_horizon"]]

    def block(key: str, h: str) -> dict[str, Any]:
        return keys[key]["by_horizon"][h]["forecasters"][key]

    def brier(key: str, h: str, model: str) -> float:
        return block(key, h)["models"][model]["brier"]

    def delta(key: str, h: str) -> dict[str, Any]:
        return block(key, h)["models"]["pool"]["delta_vs_market_recal"]["brier"]

    questions = list(read_jsonl(study.questions_path))
    snapshots = Counter(r["horizon"] for r in read_jsonl(study.snapshots_path))

    test_rows = {block(k, "all")["n_test"] for k in base}
    _require(len(test_rows) == 1, "the same test rows for every model")

    name = _family(featured)
    header = [*(HORIZON_WORDS[h] for h in hs)]
    lines = [
        ("Market price", "market"),
        ("Market, recalibrated", "market_recal"),
        (f"{_model_name(featured)} alone", "llm"),
        (f"Market + {name} (pool)", "pool"),
    ]
    rows = ["| | " + " | ".join(header) + " |", "| --- |" + " ---: |" * len(hs)]
    for label, model in lines:
        rows.append(f"| {label} | " + " | ".join(f"{brier(featured, h, model):.3f}" for h in hs))
        rows[-1] += " |"

    llm = [brier(k, h, "llm") for k in base for h in hs]
    market = [brier(featured, h, "market") for h in hs]
    _require(min(llm) > max(market), "every model alone is worse than the market")

    fam = primary_family(ev)
    _require(not any(r["reject_h1"] or r["reject_h2"] for r in fam), "no test rejects")
    p_min = min(min(r["p_h1_holm"], r["p_h2_holm"]) for r in fam)
    gain_max = max(delta(r["key"], r["horizon"])["mean"] for r in fam)

    cells: dict[str, list[dict[str, Any]]] = {}
    for k in base:
        for cat, cell in block(k, "all").get("breakdowns", {}).get("category", {}).items():
            cells.setdefault(cat, []).append(cell)
    full = {c: v for c, v in cells.items() if len(v) == len(base)}
    leads = [
        c for c, v in full.items() if all(x["delta_pool_vs_market_recal"]["lo"] > 0 for x in v)
    ]
    lags = [
        c for c, v in full.items() if all(x["delta_pool_vs_market_recal"]["mean"] < 0 for x in v)
    ]
    _require(bool(leads) and bool(lags), "categories that lead and lag for every model")
    lead_text = []
    for c in sorted(leads, key=lambda c: -full[c][0]["n"]):
        n = {(x["n"], x["n_clusters"]) for x in full[c]}
        _require(len(n) == 1, f"the same {c} rows for every model")
        rows_, events = n.pop()
        lead_text.append(f"{c} ({rows_} test rows, {events} events)")
    lead_deltas = [x["delta_pool_vs_market_recal"]["mean"] for c in leads for x in full[c]]

    news_rows = {sum(keys[k]["by_horizon"][h]["n"] for h in hs) for k in news}
    _require(len(news_rows) == 1, "the same news rows for every model")
    news_deltas = [delta(k, h)["mean"] for k in news for h in hs]
    _require(max(news_deltas) < 0, "news pools worse at every horizon for every model")
    train = [keys[k]["by_horizon"][h]["n_train"] for k in news for h in hs]

    for k in base:
        pnl = keys[k]["pnl"]["by_group"]["all"]
        _require(pnl["models"]["llm"]["pnl"] < 0, "the LLM on its own loses money")
        _require(
            pnl["incremental_vs_market_recal"]["pool"]["lo"] <= 0,
            "the pool earns no more than the recalibrated market",
        )

    split = datetime.fromisoformat(ev["split_at"].replace("Z", "+00:00"))
    return {
        "questions": f"{len(questions):,}",
        "snapshots": f"{sum(snapshots.values()):,}",
        "split": f"{split.day} {split:%B %Y}",
        "test_rows": f"{test_rows.pop():,}",
        "table": "\n".join(rows),
        "llm_lo": f"{min(llm):.2f}",
        "llm_hi": f"{max(llm):.2f}",
        "market_first": f"{market[0]:.2f}",
        "market_last": f"{market[-1]:.2f}",
        "gain_max": f"{gain_max:.4f}",
        "tests": str(2 * len(fam)),
        "p_min": f"{p_min:.2f}",
        "models": _join([_family(k) for k in sorted(base, key=lambda k: k != featured)]),
        "leads": "On " + _join(lead_text),
        "lead_lo": f"{min(lead_deltas):.4f}",
        "lead_hi": f"{max(lead_deltas):.4f}",
        "lags": _join(sorted(c.capitalize() if i == 0 else c for i, c in enumerate(lags))),
        "news_snapshots": f"{news_rows.pop():,}",
        "news_lo": f"{-max(news_deltas):.3f}",
        "news_hi": f"{-min(news_deltas):.3f}",
        "train_lo": str(min(train)),
        "train_hi": str(max(train)),
    }


def render(study: Study, ev: dict[str, Any], featured: str) -> str:
    """The README block, markers included, wrapped at 100 columns."""
    text = TEMPLATE.format(**_fields(study, ev, featured))
    wrap = textwrap.TextWrapper(100, subsequent_indent="  ", break_on_hyphens=False)
    paragraphs = []
    for para in text.strip("\n").split("\n\n"):
        if para.startswith(("|", "!")):
            paragraphs.append(para)
            continue
        items = para.split("\n- ")
        lines = [" ".join(i.split()) for i in items]
        if para.startswith("- "):
            bullets = [i if i.startswith("- ") else "- " + i for i in lines]
            paragraphs.append("\n".join(wrap.fill(b) for b in bullets))
        else:
            paragraphs.append(textwrap.fill(lines[0], 100, break_on_hyphens=False))
    start, end = MARKERS
    return start + "\n\n".join(paragraphs) + "\n" + end


def sync(readme: Path, block: str) -> None:
    """Replace the README's generated block; refuse, changing nothing, without its markers."""
    text = readme.read_text(encoding="utf-8")
    start, end = MARKERS
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        raise SystemExit(f"{readme} needs exactly one block between the generated markers")
    head, rest = text.split(start)
    readme.write_text(head + block + rest.split(end)[1], encoding="utf-8", newline="\n")
